using Azure.Storage.Blobs;
using Azure.Storage.Blobs.Models;

namespace Juggle.Api.Features.Files;

/// <summary>Where the bytes of uploaded files are kept. A file's name and owner live in the database; only its key is here.</summary>
public interface IFileStore
{
    Task SaveAsync(string key, Stream content, string contentType, CancellationToken ct);

    Task<Stream> OpenAsync(string key, CancellationToken ct);
}

/// <summary>Files configuration: an Azure Blob Storage connection string in production, a local folder otherwise.</summary>
public sealed class FileStoreOptions
{
    public string? ConnectionString { get; init; }

    public string Container { get; init; } = "job-files";

    /// <summary>The folder for development and tests, relative to the content root.</summary>
    public string LocalPath { get; init; } = "App_Data/files";
}

/// <summary>Keeps files in a folder on disk, for development.</summary>
public sealed class LocalFileStore(string root) : IFileStore
{
    public async Task SaveAsync(string key, Stream content, string contentType, CancellationToken ct)
    {
        var path = PathOf(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        await using var file = File.Create(path);
        await content.CopyToAsync(file, ct);
    }

    public Task<Stream> OpenAsync(string key, CancellationToken ct) =>
        Task.FromResult<Stream>(File.OpenRead(PathOf(key)));

    // Keys are generated by the API, never taken from a request, but a key can't leave the folder either way.
    private string PathOf(string key) => Path.Combine(root, Path.GetFileName(key));
}

/// <summary>Keeps files in an Azure Blob Storage container, for production.</summary>
public sealed class AzureBlobFileStore(BlobContainerClient container) : IFileStore
{
    public async Task SaveAsync(string key, Stream content, string contentType, CancellationToken ct)
    {
        await container.CreateIfNotExistsAsync(cancellationToken: ct);
        await container.GetBlobClient(key).UploadAsync(
            content, new BlobUploadOptions { HttpHeaders = new BlobHttpHeaders { ContentType = contentType } }, ct);
    }

    public async Task<Stream> OpenAsync(string key, CancellationToken ct) =>
        await container.GetBlobClient(key).OpenReadAsync(cancellationToken: ct);
}
